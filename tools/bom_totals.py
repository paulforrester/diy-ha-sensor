"""Recompute the cost tables in docs/bom.md from docs/bom.csv.

Usage: python3 tools/bom_totals.py           # rewrites the parts and totals blocks in docs/bom.md
       python3 tools/bom_totals.py --print   # prints the block instead

Each CSV line has a price range (eur_low, eur_high, EUR incl. VAT per item) and a price_status that says whether
the price was live-checked, taken from a search snippet, or assumed. The tables carry those labels through, so an
estimate never reads as a quote. Delivery, customs duty and VAT on non-EU orders are listed separately in bom.md;
they are not added here.
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "docs" / "bom.csv"
MD = ROOT / "docs" / "bom.md"
START, END = "<!-- totals:start (generated by tools/bom_totals.py) -->", "<!-- totals:end -->"
PSTART, PEND = "<!-- parts:start (generated by tools/bom_totals.py) -->", "<!-- parts:end -->"

GROUPS = {
    "core": "Standard unit: option B with CO2 (MCU, radar, T/RH, lux, CO2, cables)",
    "power": "USB supply and cable",
    "consumables": "Consumables (one lot for the run)",
}
ORDERS = {"A": "A: distributor (DigiKey.fr or Mouser.fr)", "B": "B: AliExpress", "C": "C: Amazon.fr",
          "stock": "From Paul's stock"}


def status_kind(s):
    s = s.lower()
    return "live" if s.startswith("live") else "assumed" if s.startswith("assumed") else "estimated"


def eur(x):
    return f"€{x:,.0f}" if x >= 100 else f"€{x:,.2f}"


def rng(lo, hi):
    return eur(lo) if abs(hi - lo) < 0.005 else f"{eur(lo)} - {eur(hi)}"


def link(name, url):
    return f"[{name}]({url})" if url else name


def parts_table():
    rows = list(csv.DictReader(CSV.open(newline="", encoding="utf-8")))
    out = [PSTART, "", "| # | Part | Per unit | Run qty | Primary source | Alternative | Price each | Price basis | Counterfeit risk |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lo, hi = float(r["eur_low"] or 0), float(r["eur_high"] or 0)
        per = r["qty_per_unit"] if r["group"] in ("core", "power") else "—"
        out.append(f"| {r['id']} | **{r['part']}**<br>{r['spec']} | {per} | {r['qty_total']} | "
                   f"{link(r['primary_source'], r['primary_url'])} | {link(r['alt_source'], r['alt_url'])} | "
                   f"{rng(lo, hi)} | {r['price_status']} | {r['counterfeit_risk']} |")
    out += ["", PEND]
    return "\n".join(out)


def build():
    rows = list(csv.DictReader(CSV.open(newline="", encoding="utf-8")))
    per_unit = defaultdict(lambda: [0.0, 0.0])
    run = defaultdict(lambda: [0.0, 0.0])
    order = defaultdict(lambda: [0.0, 0.0])
    kinds = defaultdict(lambda: defaultdict(int))
    units = 0
    for r in rows:
        lo, hi = float(r["eur_low"] or 0), float(r["eur_high"] or 0)
        qpu, qt = int(r["qty_per_unit"]), int(r["qty_total"])
        g = r["group"]
        if g in ("core", "power") and int(r["units"]) > 1:
            units = max(units, int(r["units"]))
            per_unit[g][0] += qpu * lo
            per_unit[g][1] += qpu * hi
        run[g][0] += qt * lo
        run[g][1] += qt * hi
        order[r["order"]][0] += qt * lo
        order[r["order"]][1] += qt * hi
        kinds[g][status_kind(r["price_status"])] += 1

    def mix(g):
        k = kinds[g]
        return ", ".join(f"{k[n]} {n}" for n in ("live", "estimated", "assumed") if k[n])

    out = [START, "", f"**Per unit** (one set of parts, no spares, no delivery):", "",
           "| Build | Cost per unit | Price basis (lines) |", "|---|---|---|"]
    b = per_unit["core"]
    p = [b[0] + per_unit["power"][0], b[1] + per_unit["power"][1]]
    out.append(f"| Standard unit (option B with CO2) | {rng(*b)} | {mix('core')} |")
    out.append(f"| Standard unit + USB supply and cable | {rng(*p)} | + {mix('power')} |")
    out += ["", f"**Whole run** ({units} units plus spares and consumables):", "",
            "| Group | Total | Price basis (lines) |", "|---|---|---|"]
    tot = [0.0, 0.0]
    for g, name in GROUPS.items():
        if g in run:
            out.append(f"| {name} | {rng(*run[g])} | {mix(g)} |")
            tot[0] += run[g][0]
            tot[1] += run[g][1]
    out.append(f"| **Total, before delivery and duty** | **{rng(*tot)}** | |")
    out += ["", "**By order:**", "", "| Order | Total |", "|---|---|"]
    for o, name in ORDERS.items():
        if o in order:
            out.append(f"| {name} | {rng(*order[o])} |")
    out += ["", END]
    return "\n".join(out)


def main():
    block, parts = build(), parts_table()
    if "--print" in sys.argv:
        print(parts + "\n\n" + block)
        return
    text = MD.read_text(encoding="utf-8")
    for s_, e_, new in ((PSTART, PEND, parts), (START, END, block)):
        a, b = text.index(s_), text.index(e_) + len(e_)
        text = text[:a] + new + text[b:]
    MD.write_text(text, encoding="utf-8")
    print(f"updated {MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
